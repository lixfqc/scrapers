# -*- coding: utf-8 -*-
"""
方向校验规则（交接文档更新版）：
仅"目标国进口/准入政策"（含目标国本土政策）落库；以下三类不落库，
记 crawl_task_log status='方向不符'：
① 中国对目标国（或区域）的单边零关税/特惠（如"中国对非洲53国零关税"、"非洲产品输华零关税"）
② 目标国产品出口到中国或其他国家的政策（方向相反）
③ 纯宏观/贸易新闻（无准入、税费、车龄、认证等实质信息）
"""
import re

# 反向强信号：目标国产品输华 / 中国单边特惠 / 方向相反
REVERSE_RE = re.compile(
    r'输华|进入中国市场|丰富中国市场|中国市场|对华出口|对华|出口到中国|出口中国|出口至中国|'
    r'中国进口|中国单边|单边.{0,6}零关税|对[^，。；、]{1,15}零关税|给予.{0,8}零关税|'
    r'对[^，。；、]{1,15}特惠|特惠税率|关税优惠|最不发达国家.{0,20}(特惠|零关税)|'
    r'中国.{0,10}降税|中方.{0,10}(免关税|零关税)', re.I)

# 实质信息：目标国准入/税费/车龄/认证/排放等（命中才可能落库）
SUBSTANCE_RE = re.compile(
    r'进口规定|进口限制|进口禁令|禁止进口|禁止.{0,6}进口|准入|认证|车龄|二手车|'
    r'关税|增值税|消费税|附加税|排放|右舵|左舵|PVoC|CoC|SONCAP|'
    r'免税|降税|税率|监管|法规|法令|新规|规定|标准|要求|限制', re.I)


def check_direction(title, content_text):
    """
    方向校验
    返回 ('OK', '') 或 ('方向不符', reason)
    """
    text = f'{title or ""}\n{content_text or ""}'
    if REVERSE_RE.search(text):
        return '方向不符', '方向相反：中国单边零关税/特惠、产品输华或目标国出口政策'
    if SUBSTANCE_RE.search(text):
        return 'OK', ''
    return '方向不符', '纯宏观/贸易新闻：无准入、税费、车龄、认证等实质信息'
